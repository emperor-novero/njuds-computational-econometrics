"""NJ Long-Term Tax Exemption (PILOT) & Five-Year Abatement Modeling.

Statutory computational models for municipal tax incentive agreements under:
1. Long Term Tax Exemption Law: N.J.S.A. 40A:20-1 et seq. (Payment In Lieu Of Taxes / PILOT)
2. Five-Year Exemption and Abatement Law: N.J.S.A. 40A:21-1 et seq.

Calculates Annual Service Charges (ASC), County 5% Statutory Remittance,
Conventional vs. PILOT Tax Arbitrage, School Board Revenue Displacement,
and Net Present Value (NPV) of long-term tax abatements.
"""

from dataclasses import dataclass
from typing import Dict, List, Optional


@dataclass
class PILOTComparisonResult:
    """Forensic comparison between Conventional Ad Valorem Tax and PILOT ASC."""
    property_name: str
    municipality: str
    annual_gross_revenue: float
    total_project_cost: float
    conventional_assessed_value: float
    general_tax_rate: float
    conventional_tax_liability: float
    pilot_asc_rate: float
    pilot_asc_amount: float
    land_taxes_paid: float
    net_service_charge_due: float
    annual_tax_savings: float
    tax_savings_percentage: float
    county_5pct_share: float
    municipal_95pct_retention: float
    school_direct_allocation: float  # Under standard PILOT, schools receive $0 direct statutory share


@dataclass
class FiveYearPhaseInResult:
    """Schedule of tax liabilities under N.J.S.A. 40A:21 Five-Year Abatement."""
    year: int
    abatement_phase_pct: float
    exempt_improvement_value: float
    taxable_improvement_value: float
    improvement_tax_due: float
    land_tax_due: float
    total_tax_due: float
    annual_savings: float


class NJPILOTEngine:
    """Computational modeling engine for New Jersey PILOT and Abatement agreements."""

    @classmethod
    def evaluate_pilot_agreement(
        cls,
        property_name: str,
        municipality: str,
        annual_gross_revenue: float,
        total_project_cost: float,
        conventional_assessed_value: float,
        general_tax_rate: float,
        pilot_asc_rate: float = 0.10,
        land_assessed_value: float = 0.0,
        minimum_annual_service_charge: float = 0.0,
        calc_basis: str = "AGR"  # "AGR" (Annual Gross Revenue) or "TPC" (Total Project Cost)
    ) -> PILOTComparisonResult:
        """Calculates Annual Service Charge (ASC) vs Conventional Real Estate Tax.
        
        Args:
            property_name: Label or address of the development project.
            municipality: Name of the taxing municipality.
            annual_gross_revenue: Annual gross revenue (AGR) generated by the project.
            total_project_cost: Total audited construction and land cost (TPC).
            conventional_assessed_value: What the property would be assessed at without PILOT.
            general_tax_rate: General tax rate per $100 of assessed valuation (e.g., 3.50 for $3.50 per $100).
            pilot_asc_rate: Statutory ASC rate (e.g. 0.10 for 10% of AGR, or 0.02 for 2% of TPC).
            land_assessed_value: Assessed value of the land parcel.
            minimum_annual_service_charge: Pre-redevelopment tax floor (N.J.S.A. 40A:20-12).
            calc_basis: Basis for ASC: 'AGR' (Annual Gross Revenue) or 'TPC' (Total Project Cost).
            
        Returns:
            PILOTComparisonResult detailing tax arbitrage and statutory fund splits.
        """
        # Conventional property tax: (Assessed Value / 100) * General Tax Rate
        conventional_tax = (conventional_assessed_value / 100.0) * general_tax_rate
        land_tax = (land_assessed_value / 100.0) * general_tax_rate

        # Calculate raw ASC based on formula
        if calc_basis.upper() == "TPC":
            raw_asc = total_project_cost * pilot_asc_rate
        else:
            raw_asc = annual_gross_revenue * pilot_asc_rate

        # Enforce Minimum Annual Service Charge floor (N.J.S.A. 40A:20-12)
        base_asc = max(raw_asc, minimum_annual_service_charge)

        # Land tax credit: Land tax paid is credited against ASC or paid in full
        # If ASC > land tax, ASC is payable with credit; if land tax > ASC, entity pays land tax.
        effective_asc = max(base_asc, land_tax)
        net_service_charge_due = effective_asc

        # Tax savings compared to conventional ad valorem
        savings = conventional_tax - effective_asc
        savings_pct = (savings / conventional_tax * 100.0) if conventional_tax > 0 else 0.0

        # Statutory Distribution under N.J.S.A. 40A:20-12:
        # County receives exactly 5% of the annual service charge collected.
        # Municipality retains 95%. School district receives 0% direct statutory allocation.
        county_share = effective_asc * 0.05
        muni_share = effective_asc * 0.95
        school_share = 0.0

        return PILOTComparisonResult(
            property_name=property_name,
            municipality=municipality,
            annual_gross_revenue=round(annual_gross_revenue, 2),
            total_project_cost=round(total_project_cost, 2),
            conventional_assessed_value=round(conventional_assessed_value, 2),
            general_tax_rate=general_tax_rate,
            conventional_tax_liability=round(conventional_tax, 2),
            pilot_asc_rate=pilot_asc_rate,
            pilot_asc_amount=round(effective_asc, 2),
            land_taxes_paid=round(land_tax, 2),
            net_service_charge_due=round(net_service_charge_due, 2),
            annual_tax_savings=round(savings, 2),
            tax_savings_percentage=round(savings_pct, 2),
            county_5pct_share=round(county_share, 2),
            municipal_95pct_retention=round(muni_share, 2),
            school_direct_allocation=round(school_share, 2)
        )

    @classmethod
    def calculate_five_year_abatement_schedule(
        cls,
        pre_rehab_land_assessed_value: float,
        improvement_added_value: float,
        general_tax_rate: float
    ) -> List[FiveYearPhaseInResult]:
        """Calculates statutory 5-year phase-in tax schedule under N.J.S.A. 40A:21-10.
        
        The standard statutory phase-in formula taxes the improvement as follows:
        - Year 1: 0% of full improvement value
        - Year 2: 20%
        - Year 3: 40%
        - Year 4: 60%
        - Year 5: 80%
        - Year 6: 100% (fully taxable)
        Land value is always taxed at 100% in all years.
        
        Returns:
            List of 5 FiveYearPhaseInResult objects tracking year-by-year liabilities and savings.
        """
        schedule = []
        phase_rates = [0.00, 0.20, 0.40, 0.60, 0.80]
        land_tax = (pre_rehab_land_assessed_value / 100.0) * general_tax_rate
        full_improvement_tax = (improvement_added_value / 100.0) * general_tax_rate

        for idx, rate in enumerate(phase_rates, start=1):
            taxable_imp = improvement_added_value * rate
            exempt_imp = improvement_added_value * (1.0 - rate)
            imp_tax = (taxable_imp / 100.0) * general_tax_rate
            total_tax = land_tax + imp_tax
            savings = full_improvement_tax - imp_tax

            schedule.append(FiveYearPhaseInResult(
                year=idx,
                abatement_phase_pct=rate,
                exempt_improvement_value=round(exempt_imp, 2),
                taxable_improvement_value=round(taxable_imp, 2),
                improvement_tax_due=round(imp_tax, 2),
                land_tax_due=round(land_tax, 2),
                total_tax_due=round(total_tax, 2),
                annual_savings=round(savings, 2)
            ))

        return schedule

    @classmethod
    def calculate_pilot_net_present_value(
        cls,
        initial_annual_savings: float,
        duration_years: int = 30,
        discount_rate: float = 0.07,
        annual_growth_rate: float = 0.02
    ) -> float:
        """Calculates Net Present Value (NPV) of a long-term PILOT tax shield to equity.
        
        Args:
            initial_annual_savings: Year 1 tax savings (conventional tax minus ASC).
            duration_years: Term of the financial agreement (e.g. 20, 30 years).
            discount_rate: WACC or equity discount rate (e.g., 0.07 for 7.0%).
            annual_growth_rate: Projected annual escalation in tax differential.
            
        Returns:
            Total Net Present Value of the tax shield in USD.
        """
        npv = 0.0
        current_savings = initial_annual_savings

        for year in range(1, duration_years + 1):
            discount_factor = (1.0 + discount_rate) ** year
            npv += current_savings / discount_factor
            current_savings *= (1.0 + annual_growth_rate)

        return round(npv, 2)
