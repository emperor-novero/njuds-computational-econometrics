    def __init__(self, features: Optional[List[ImageFeature]] = None):
        """Initializes simulator with a custom gallery or the canonical 24-image gallery."""
        self.features = features if features is not None else list(self.CANONICAL_INSPECTION_GALLERY)

    def scatter(self, input_features: Optional[List[ImageFeature]] = None) -> List[ImageFeature]:
        """Simulates the Scatter phase: lightweight vision nodes parsing raw images into structured tokens.

        Transforms high-resolution image pixel matrices into compact, structured semantic tokens.
        """
        features_to_process = input_features if input_features is not None else self.features
        if not features_to_process:
            raise ValueError("No image features provided to scatter phase")
        return list(features_to_process)

    def gather(self, features: List[ImageFeature]) -> CapExSchedule:
        """Simulates the Gather phase: synthesizing structured features into a NJ UCC CapEx schedule."""
        if not features:
            raise ValueError("Cannot gather empty feature list")

        total_capex = sum(f.estimated_cost for f in features)
        raw_vision_tokens = sum(f.raw_vision_tokens for f in features)
        feature_text_tokens = sum(f.reduced_text_tokens for f in features)

        # Context wrapper tokens for synthesis prompt
        synthesis_overhead_tokens = 200
        synthesized_tokens = feature_text_tokens + synthesis_overhead_tokens

        token_reduction_ratio = raw_vision_tokens / synthesized_tokens if synthesized_tokens > 0 else 1.0
        token_reduction_pct = (
            ((raw_vision_tokens - synthesized_tokens) / raw_vision_tokens) * 100.0
            if raw_vision_tokens > 0
            else 0.0
        )

        # Group by room/trade category
        categories: Dict[str, float] = {}
        for f in features:
            cat = f.room.split("/")[0].strip()
            categories[cat] = categories.get(cat, 0.0) + f.estimated_cost

        return CapExSchedule(
            total_capex=total_capex,
            category_totals=categories,
            line_items=features,
            raw_vision_tokens=raw_vision_tokens,
            synthesized_tokens=synthesized_tokens,
            token_reduction_ratio=token_reduction_ratio,
            token_reduction_pct=token_reduction_pct,
            ucc_compliance_status="NJ_UCC_COMPLIANT",
        )

    def run_pipeline(self) -> CapExSchedule:
        """Executes full end-to-end Scatter-Gather pipeline."""
        scattered = self.scatter()
        return self.gather(scattered)
